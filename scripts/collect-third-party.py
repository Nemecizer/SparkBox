#!/usr/bin/env python3
"""Collect installed dependency notices without embedding local cache paths."""
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT/'third-party'
if OUT.exists():
    raise SystemExit('third-party already exists; review it before replacing it')
OUT.mkdir()
entries = []


def notice_files(folder):
    matches=[]
    for p in folder.rglob('*'):
        if not p.is_file() or p.is_symlink(): continue
        rel=p.relative_to(folder)
        if 'node_modules' in rel.parts or len(rel.parts)>5: continue
        if re.match(r'(?i)^(license|licence|copying|copyright|notice|unlicense)([._-].*)?$',p.name): matches.append(p)
    return sorted(matches)


def add(ecosystem,name,version,folder,license_name,extra=None):
    ident=re.sub(r'[^A-Za-z0-9._-]','_',f'{name}-{version}')
    target=OUT/'licenses'/ecosystem/ident
    notices=notice_files(folder)
    if extra and extra.is_file() and extra not in notices: notices.append(extra)
    saved=[]
    for p in notices:
        relative=p.relative_to(folder)
        dest=target/relative;dest.parent.mkdir(parents=True,exist_ok=True)
        shutil.copyfile(p,dest)
        saved.append({'path':str(dest.relative_to(ROOT)), 'sha256':hashlib.sha256(dest.read_bytes()).hexdigest()})
    entries.append({'ecosystem':ecosystem,'name':name,'version':version,'license':license_name,'notices':saved})


lock=json.loads((ROOT/'package-lock.json').read_text())
for path,info in lock['packages'].items():
    if not path:continue
    folder=ROOT/path
    if not (folder/'package.json').is_file():continue  # Optional packages for another platform.
    package=json.loads((folder/'package.json').read_text())
    add('npm',package['name'],package['version'],folder,package.get('license',info.get('license')))

metadata=json.loads(subprocess.check_output(['cargo','metadata','--locked','--offline','--format-version','1'],cwd=ROOT/'src-tauri'))
for package in metadata['packages']:
    if package['source'] is None:continue
    folder=Path(package['manifest_path']).parent
    extra=folder/package['license_file'] if package.get('license_file') else None
    add('cargo',package['name'],package['version'],folder,package.get('license'),extra)

# Only modules used by this helper's imports, not every unused gvisor test dependency.
raw=subprocess.check_output(['go','list','-deps','-json','./...'],cwd=ROOT/'tunnel',text=True)
decoder=json.JSONDecoder(); modules={}
while raw.strip():
    obj,n=decoder.raw_decode(raw.lstrip());raw=raw.lstrip()[n:]
    mod=obj.get('Module',{})
    if not mod.get('Main') and mod.get('Dir') and mod.get('Version'):modules[mod['Path']]=mod
for mod in modules.values():add('go',mod['Path'],mod['Version'],Path(mod['Dir']),'See copied upstream notices')

entries.sort(key=lambda p:(p['ecosystem'],p['name'],p['version']))
(OUT/'inventory.json').write_text(json.dumps(entries,indent=2)+'\n')
missing=[f"{e['ecosystem']} {e['name']} {e['version']} ({e['license']})" for e in entries if not e['notices']]
(OUT/'README.md').write_text('# Dependency notices\n\nGenerated by scripts/collect-third-party.py from the locked installed packages for an Apple Silicon macOS build. Includes installed npm packages, Cargo resolved packages and Go modules actually imported by the helper. Build/test dependencies and some other-platform Cargo packages are included conservatively. Optional npm binaries for other platforms are not installed here. This inventory does not relicense upstream code.\n\nLicense/notice file contents are copied unchanged. Local cache paths and credentials are not included. Read inventory.json for package names, versions, reported licenses and notice hashes.\n\nPackages with no discovered notice file:\n\n'+('\n'.join('- '+x for x in missing) if missing else 'None.')+'\n')
print(json.dumps({'packages':len(entries),'notices':sum(len(e['notices']) for e in entries),'missing_notices':missing}))

if missing:
    raise SystemExit("Notice collection is incomplete; review missing packages before distribution")
